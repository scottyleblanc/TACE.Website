#Requires -Version 7.6

<#
.SYNOPSIS
    Records the current analyzer findings as the repository's baseline (rule AN-001).

.DESCRIPTION
    Runs the same analysis as gate check GK03 and writes every finding, counted per
    file and rule, to the file gate.config.psd1 names under Analyzer.Baseline. GK03
    then fails only on findings beyond those counts.

    Use it once when a repository with existing findings adopts the gate, and after
    fixing findings, to shrink the baseline. Never use it to admit a new finding: fix
    the finding, or suppress it with a justified SuppressMessageAttribute.

.EXAMPLE
    pwsh -NoProfile -File ./tools/gate/Scripts/Update-AnalyzerBaseline.ps1

    Rewrites the baseline. Review the diff before committing it: a count that grows is
    a new finding.

.NOTES
    **Invocation:** Standalone — self-contained; safe to run with `pwsh -File`. Needs
    PSScriptAnalyzer 1.25.0 and Analyzer.Baseline set in gate.config.psd1.
#>
[CmdletBinding(SupportsShouldProcess)]
[OutputType([string])]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path -Path $PSScriptRoot -ChildPath 'Lib' -AdditionalChildPath 'GateLib.ps1')

$kitRoot  = Split-Path -Path $PSScriptRoot -Parent
$repoRoot = Get-GateRepoRoot -Path $PSScriptRoot

$config = $null
$loaded = Import-GateConfig -RepoRoot $repoRoot
# The baseline file may not exist yet; that one problem is expected here.
$problems = @($loaded.Problems | Where-Object { $PSItem -notmatch '^gate\.config\.psd1: Analyzer\.Baseline names ' })
if ($problems.Count -gt 0) { throw "[Update-AnalyzerBaseline] gate.config.psd1 is not valid: $($problems -join '; ')" }
$config = $loaded.Config
if (-not $config.Analyzer.Baseline) { throw '[Update-AnalyzerBaseline] Set Analyzer.Baseline in gate.config.psd1 to the file to write.' }

Import-Module -Name PSScriptAnalyzer -RequiredVersion 1.25.0
$analysis = Invoke-GateAnalyzer -RepoRoot $repoRoot -KitRoot $kitRoot -Config $config
$groups   = @($analysis.Findings | Group-Object -Property Path, Rule | Sort-Object -Property Name)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('@{')
$lines.Add('    # Analyzer findings accepted when the gate was adopted (rule AN-001), counted per')
$lines.Add('    # file and rule. Generated by Update-AnalyzerBaseline.ps1; do not edit by hand.')
$lines.Add('    # A count may only go down.')
$lines.Add('    Findings = @(')
foreach ($group in $groups) {
    $first = $group.Group[0]
    $lines.Add("        @{ Path = '$($first.Path.Replace("'", "''"))'; Rule = '$($first.Rule)'; Count = $($group.Count) }")
}
$lines.Add('    )')
$lines.Add('}')

$target = Resolve-GatePath -RepoRoot $repoRoot -RelativePath $config.Analyzer.Baseline
if ($PSCmdlet.ShouldProcess($config.Analyzer.Baseline, "Write $($analysis.Findings.Count) finding(s) in $($groups.Count) file and rule pair(s)")) {
    $null = New-Item -Path (Split-Path -Path $target -Parent) -ItemType Directory -Force
    [System.IO.File]::WriteAllText($target, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Output "[INFO] $($config.Analyzer.Baseline): $($analysis.Findings.Count) finding(s) in $($groups.Count) file and rule pair(s)"
}
